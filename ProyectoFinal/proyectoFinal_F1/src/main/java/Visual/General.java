private void ocultarClaves() {

    javax.swing.table.TableColumnModel columnas =
            jTable1.getColumnModel();

    String[] nombresClaves = {
        "Identificador",
        "Código",
        "Código piloto",
        "ID auto",
        "ID Gran Premio"
    };

    for (int i = columnas.getColumnCount() - 1; i >= 0; i--) {

        String nombre = columnas.getColumn(i)
                .getHeaderValue().toString();

        for (String clave : nombresClaves) {

            if (nombre.equalsIgnoreCase(clave)) {
                columnas.removeColumn(columnas.getColumn(i));
                break;
            }
        }
    }
}

