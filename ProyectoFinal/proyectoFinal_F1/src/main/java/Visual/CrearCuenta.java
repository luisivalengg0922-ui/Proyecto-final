    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
String usuario = jTextField3.getText().trim();

String contrasena = new String(jPasswordField1.getPassword());
String confirmar = new String(jPasswordField2.getPassword());

// Verificar que no haya campos vacíos
if (usuario.isEmpty() || contrasena.isEmpty() || confirmar.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Completa todos los campos."
    );
    return;
}

// Verificar que ambas contraseñas coincidan
if (!contrasena.equals(confirmar)) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Las contraseñas no coinciden."
    );
    return;
}

// Registrar la cuenta en MySQL
boolean registrado = Fachada.getInstancia()
        .registrarUsuario(usuario, contrasena);

if (registrado) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Cuenta creada correctamente."
    );

    new Login().setVisible(true);
    this.dispose();

} else {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "No se pudo crear la cuenta. "
            + "Comprueba la conexión con MySQL "
            + "o si el usuario ya existe."
    );
}

    }//GEN-LAST:event_jButton1ActionPerformed

