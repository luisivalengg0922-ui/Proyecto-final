    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String usuario = jTextField3.getText().trim();
    String contrasena = new String(jPasswordField1.getPassword());

    if (usuario.isEmpty() || contrasena.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Introduce usuario y contraseña."
        );

        return;
    }

    boolean valido = Fachada.getInstancia()
            .validarLogin(usuario, contrasena);

    if (!valido) {

        JOptionPane.showMessageDialog(
                this,
                "Usuario o contraseña incorrectos."
        );

        return;
    }

    if (usuario.equals("admin") && contrasena.equals("1234abc")) {

        JOptionPane.showMessageDialog(
                this,
                "Sesión de administrador iniciada."
        );

        new Generalroot().setVisible(true);

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Inicio de sesión correcto."
        );

        new General().setVisible(true);
    }

    this.dispose();

    }//GEN-LAST:event_jButton1ActionPerformed

